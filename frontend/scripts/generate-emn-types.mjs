import fs from 'node:fs/promises'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

import {compile} from 'json-schema-to-typescript'

const frontendDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const exportDirectory = path.join(frontendDirectory, 'build/generated/resources/emn-schemas')
const manifestPath = path.join(exportDirectory, 'manifest.json')
const outputPath = path.join(frontendDirectory, 'build/generated/sources/emn/quizmania-api.ts')

const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'))
const definitions = Object.fromEntries(await Promise.all(manifest.schemas.map(async schemaEntry => {
  const schemaPath = path.join(exportDirectory, schemaEntry.file)
  return [schemaEntry.typeId, JSON.parse(await fs.readFile(schemaPath, 'utf8'))]
})))

const discriminatorMappings = new Map(Object.entries(definitions)
  .filter(([, schema]) => schema.discriminator?.mapping)
  .map(([typeId, schema]) => [typeId, Object.values(schema.discriminator.mapping)]))
const discriminatorBaseByMappedType = new Map([...discriminatorMappings]
  .flatMap(([baseTypeId, mappedTypeIds]) => mappedTypeIds.map(mappedTypeId => [mappedTypeId, `${baseTypeId}Base`])))

for (const [typeId, mappedTypeIds] of discriminatorMappings) {
  const baseTypeId = `${typeId}Base`
  if (definitions[baseTypeId]) {
    throw new Error(`Cannot generate discriminator base type ${baseTypeId}: that type already exists`)
  }

  definitions[baseTypeId] = {...definitions[typeId], title: baseTypeId}
  definitions[typeId] = {
    title: typeId,
    oneOf: mappedTypeIds.map(mappedTypeId => ({$ref: `#/$defs/${mappedTypeId}`}))
  }
}

const transformSchema = (value, ownerTypeId) => {
  if (Array.isArray(value)) {
    return value.map(entry => transformSchema(entry, ownerTypeId))
  }
  if (value === null || typeof value !== 'object') {
    return value
  }

  return Object.fromEntries(Object.entries(value).flatMap(([key, entryValue]) => {
    if (key === '$id' || key.startsWith('x-emn-') || key === 'discriminator') {
      return []
    }

    if (key === '$ref' && typeof entryValue === 'string') {
      const referencedTypeId = path.basename(entryValue, '.schema.json')
      const effectiveTypeId = discriminatorMappings.has(referencedTypeId)
        && discriminatorBaseByMappedType.has(ownerTypeId)
        ? `${referencedTypeId}Base`
        : referencedTypeId
      return [[key, `#/$defs/${effectiveTypeId}`]]
    }

    return [[key, transformSchema(entryValue, ownerTypeId)]]
  }))
}

const transformedDefinitions = Object.fromEntries(Object.entries(definitions)
  .map(([typeId, schema]) => [typeId, transformSchema(schema, typeId)]))

// The public discriminator type must reference its implementations, not its base.
for (const [typeId, mappedTypeIds] of discriminatorMappings) {
  transformedDefinitions[typeId] = {
    title: typeId,
    oneOf: mappedTypeIds.map(mappedTypeId => ({$ref: `#/$defs/${mappedTypeId}`}))
  }
}

const rootSchema = {
  title: 'QuizmaniaApi',
  anyOf: manifest.schemas.map(({typeId}) => ({$ref: `#/$defs/${typeId}`})),
  $defs: transformedDefinitions
}

const generatedTypes = await compile(rootSchema, 'QuizmaniaApi', {
  additionalProperties: false,
  bannerComment: `/* eslint-disable */
/**
 * Generated from doc/quizmania-blueprint.emn via the EMN schema export.
 * Do not edit this file directly.
 */`,
  enableConstEnums: false,
  style: {
    bracketSpacing: false,
    printWidth: 120,
    semi: false,
    singleQuote: true,
    tabWidth: 2,
    trailingComma: 'none',
    useTabs: false
  }
})

const typeIdsByKind = kind => manifest.schemas
  .filter(schema => schema.kind === kind)
  .map(schema => schema.typeId)

const union = (name, typeIds) => `export type ${name} =\n${typeIds.map(typeId => `  | ${typeId}`).join('\n')}\n`
const tsString = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const typeMap = (name, typeIds) => `export interface ${name} {\n${typeIds
  .map(typeId => `  ${tsString(typeId)}: ${typeId}`)
  .join('\n')}\n}\n`
const enumConstants = manifest.schemas.flatMap(({typeId}) => {
  const enumValues = definitions[typeId].enum
  if (!Array.isArray(enumValues) || !enumValues.every(value => typeof value === 'string')) {
    return []
  }

  return [`export const ${typeId} = {\n${enumValues
    .map(value => `  ${tsString(value)}: ${tsString(value)}`)
    .join(',\n')}\n} as const\n`]
}).join('\n')
const commandTypeIds = typeIdsByKind('command')
const eventTypeIds = typeIdsByKind('event')
const generatedApi = `${generatedTypes.trim()}\n\n${enumConstants}\n${typeMap('GameCommandPayloadByType', commandTypeIds)}
export type GameCommandType = keyof GameCommandPayloadByType\n\n${union('GameCommandPayload', commandTypeIds)}\n${typeMap('GameEventPayloadByType', eventTypeIds)}
export type GameEventType = keyof GameEventPayloadByType\n\n${union('GameEventPayload', eventTypeIds)}`

await fs.mkdir(path.dirname(outputPath), {recursive: true})
await fs.writeFile(outputPath, generatedApi)

console.log(`Generated ${manifest.schemas.length} EMN schema types in ${path.relative(frontendDirectory, outputPath)}`)
